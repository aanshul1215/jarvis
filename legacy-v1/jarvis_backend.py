# 3) LLM call function
def call_llm(prompt: str,
             system_message: str = SYSTEM_MESSAGE,
             model: str = "gpt-3.5-turbo",
             temperature: float = 0.2,
             max_tokens: int = 400,
             log_path: str = "jarvis_llm_log.csv") -> str | dict:
    """
    Sends a single user prompt (with a SYSTEM_MESSAGE) to the OpenAI ChatCompletion API,
    returns the assistant response as a string, or {'error': ...} on failure.
    Logs timestamp, model, prompt snippet, and response/error to CSV.
    """
    # Prepare log entry
    log_row = {
        "timestamp": datetime.utcnow().isoformat(),
        "model": model,
        "temperature": temperature,
        "prompt": prompt.replace("\n", "\\n")[:2000],
        "response": "",
        "error": ""
    }

    messages = [
        {"role": "system", "content": system_message},
        {"role": "user",   "content": prompt}
    ]

    try:
        resp = openai.chat.completions.create(
            model= model,
            messages= messages,
            temperature= temperature,
            max_tokens= max_tokens,
        )
        answer = resp.choices[0].message.content.strip()
        log_row["response"] = answer.replace("\n", "\\n")
        return answer

    except Exception as e:
        log_row["error"] = str(e)
        return {"error": str(e)}

    finally:
        # Write header if needed
        write_header = not os.path.exists(log_path)
        with open(log_path, "a", encoding="utf-8") as f:
            if write_header:
                f.write(",".join(log_row.keys()) + "\n")
            # quote values, remove any stray quotes
            row = []
            for v in log_row.values():
                clean = str(v).replace('"', '')
                row.append(f'"{clean}"')
            f.write(",".join(row) + "\n")

