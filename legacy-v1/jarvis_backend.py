def link_drivers_to_news(top_drivers, feature_explain, news_list):
    linked = []
    for driver in top_drivers:
        expl = feature_explain.get(driver, driver)
        driver_words = set(expl.lower().replace("(", "").replace(")", "").split())
        matches = []
        for n in news_list:
            n_words = set(n.lower().split())
            if driver_words & n_words:  # intersection
                matches.append(n)
        linked.append((driver, expl, matches))
    return linked

def drivers_to_narrative(linked_drivers):
    lines = []
    for driver, expl, news_matches in linked_drivers:
        if news_matches:
            lines.append(f"{expl} — related news: “{news_matches[0]}”.")
        else:
            lines.append(f"{expl} was a key factor.")
    return " ".join(lines)

