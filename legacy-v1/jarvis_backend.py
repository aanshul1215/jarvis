def extract_jarvis_params(user_query: str):
    """
    Parses a user's query into:
      - intent: one of INTENT_KEYWORDS keys or 'fallback'
      - asset: ticker symbol (e.g. 'TSLA') or None
      - date: datetime.date or None
      - aspect: for deep dives ('sentiment','technical','sec') or None
    """
    q = user_query.lower()
    params = {"intent": "fallback", "asset": None, "date": None, "aspect": None}

    # 1) Greeting → immediate
    for kw in INTENT_KEYWORDS["greeting"]:
        if kw in q:
            params["intent"] = "greeting"
            return params

    # 2) Intent matching (first match wins)
    for intent, kws in INTENT_KEYWORDS.items():
        if intent == "greeting":
            continue
        if any(kw in q for kw in kws):
            params["intent"] = intent
            break

    # 3) Asset detection
    for name, ticker in TICKER_MAP.items():
        if name in q:
            params["asset"] = ticker
            break

    # 4) Date detection
    if "today" in q:
        params["date"] = pd.Timestamp("today").date()
    elif "tomorrow" in q:
        params["date"] = (pd.Timestamp("today") + pd.Timedelta(days=1)).date()
    else:
        found = search_dates(user_query, settings={"PREFER_DATES_FROM": "future"})
        if found:
            params["date"] = found[0][1].date()

    # 5) Aspect for deep dives
    if params["intent"].startswith("deep_"):
        params["aspect"] = params["intent"].split("_", 1)[1]

    return params

